import datetime
import json
import pprint
from collections.abc import AsyncGenerator

import fastapi
import httpx
import openai

import duckduckgo


_UPSTREAM_URL = "http://192.168.86.14:8000/v3/chat/completions"


app = fastapi.FastAPI()


@app.get("/")
def usage():
    return fastapi.responses.HTMLResponse(
        content="<p>Set your OpenAI API client to use <b>/v1/chat/completions</b></p>"
    )


